package com.music.spotui.ui.immersive.squared.glass.backdrop.effects

import androidx.compose.ui.graphics.RenderEffect
import com.music.spotui.ui.immersive.squared.glass.backdrop.BackdropEffectScope
import com.music.spotui.ui.immersive.squared.glass.backdrop.RuntimeShader
import com.music.spotui.ui.immersive.squared.glass.backdrop.internal.RuntimeShaderEffect
import com.music.spotui.ui.immersive.squared.glass.backdrop.internal.chain
import com.music.spotui.ui.immersive.squared.glass.backdrop.isRenderEffectSupported
import com.music.spotui.ui.immersive.squared.glass.backdrop.isRuntimeShaderSupported
import org.intellij.lang.annotations.Language
import kotlin.contracts.ExperimentalContracts

fun BackdropEffectScope.effect(effect: RenderEffect) {
    if (!isRenderEffectSupported()) return

    renderEffect = renderEffect.chain(effect)
}

@OptIn(ExperimentalContracts::class)
fun BackdropEffectScope.runtimeShaderEffect(
    key: String,
    @Language("AGSL") shaderString: String,
    uniformShaderName: String,
    block: RuntimeShader.() -> Unit
) {
    if (!isRuntimeShaderSupported()) return

    val effect =
        RuntimeShaderEffect(
            runtimeShader = obtainRuntimeShader(key, shaderString).apply(block),
            uniformShaderName = uniformShaderName
        )
    renderEffect = renderEffect.chain(effect)
}
